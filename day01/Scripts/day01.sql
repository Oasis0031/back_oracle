-- 선물 테이블(TBL_GIFT)
-- 선물 주소, 선물 수량, 상품 아이디
CREATE SEQUENCE SEQ_GIFT;
CREATE TABLE TBL_GIFT(
	ID NUMBER CONSTRAINT PK_GIFT PRIMARY KEY,
	GIFT_ADDRESS VARCHAR2(255) NOT NULL,
	GIFT_AMOUNT VARCHAR2(255) NOT NULL,
	PRODUCT_ID NUMBER,
	CONSTRAINT FK_GIFT_PRODUCT_ID FOREIGN KEY(PRODUCT_ID)
	REFERENCES TBL_PRODUCT(ID)	
);

